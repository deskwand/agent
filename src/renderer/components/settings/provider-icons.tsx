interface ProviderBrandIconProps {
  /** provider 键；未知值（custom/ollama/oauth 等）渲染通用 Server 图标 */
  brand: ProviderBrand | ProviderType;
  className?: string;
}

export function ProviderBrandIcon({
  brand,
  className = "h-5 w-5",
}: ProviderBrandIconProps) {
  const spec = BRAND_SPECS[brand as ProviderBrand];
  if (!spec) {
    return <Server className={className} aria-hidden="true" />;
  }
  return (
    <svg
      viewBox="0 0 24 24"
      aria-hidden="true"
      className={`${spec.fill} ${className}`}
    >
      <path d={spec.path} />
    </svg>
  );
}
