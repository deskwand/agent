/**
 * 将 provider（及 custom 的协议）解析为品牌键；
 * 无法映射时（ollama/oauth/未知协议）返回 undefined，由调用方走 Server 兑底。
 */
export function resolveProviderBrand(
  provider: ProviderType,
  customProtocol?: CustomProtocolType,
): ProviderBrand | undefined {
  if (provider !== "custom") {
    return BRAND_SPECS[provider as ProviderBrand]
      ? (provider as ProviderBrand)
      : undefined;
  }
  if (customProtocol === "openai") return "openai";
  if (customProtocol === "gemini") return "gemini";
  if (customProtocol === "anthropic") return "anthropic";
  return undefined;
}

