import type { ToolDefinition } from "@earendil-works/pi-coding-agent";
import type { TSchema } from "@sinclair/typebox";
import type { Message, Session } from "../../renderer/types";
import type { AskUserPromptList, AskUserResult } from "../../shared/ask-user";

export type AgentRuntimeCustomTool = ToolDefinition<TSchema, unknown>;

export interface BeforeSessionRunContext {
  session: Session;
  prompt: string;
  existingMessages: Message[];
  isColdStart: boolean;
}

export interface BeforeSessionRunResult {
  promptPrefix?: string;
  systemPromptSuffix?: string;
  customTools?: AgentRuntimeCustomTool[];
  /** Vetoes tool calls for this session run; see ToolCallGuard. */
  toolCallGuard?: ToolCallGuard;
}

export interface AfterSessionRunContext {
  session: Session;
  prompt: string;
  messages: Message[];
  /** 本轮结果：runner 内部吞掉的模型错误只体现在这里（不会走 onSessionRunError）。 */
  outcome?: "success" | "failure" | "cancelled" | "unknown";
}

export interface AfterSessionRunResult {
  continuePrompt?: string;
  goalStatus?: {
    status:
      | "active"
      | "paused"
      | "complete"
      | "cleared"
      | "blocked"
      | "budget_limited";
    objective?: string;
    iteration?: number;
    tokensUsed?: number;
    tokenBudget?: number;
    timeUsedSeconds?: number;
    timeBudgetSeconds?: number;
    activePeriodStartedAt?: number;
  };
  summaryMessage?: string;
}

export interface CommandContext {
  command: string;
  args: string;
  sessionId: string;
}

export interface CommandResult {
  handled: boolean;
  message?: string;
  firstTurnPrompt?: string;
  goalStatus?: AfterSessionRunResult["goalStatus"];
  clearAutoGenerated?: boolean;
}

export interface SessionDeletedContext {
  sessionId: string;
  session?: Session | null;
}

export interface SessionRunErrorContext {
  sessionId: string;
  error: unknown;
}

export interface AgentRuntimeExtension {
  name: string;
  beforeSessionRun?(
    context: BeforeSessionRunContext,
  ): Promise<BeforeSessionRunResult | void>;
  afterSessionRun?(
    context: AfterSessionRunContext,
  ): Promise<AfterSessionRunResult | void>;
  onCommand?(context: CommandContext): Promise<CommandResult | void>;
  onSessionDeleted?(context: SessionDeletedContext): Promise<void>;
  onSessionRunError?(
    context: SessionRunErrorContext,
  ): Promise<AfterSessionRunResult | void>;
}

export interface ToolCallGuardContext {
  /** Absent when the session cannot show cards (e.g. no requestAskUser wired). */
  askUser?: (questions: AskUserPromptList) => Promise<AskUserResult>;
}

export type ToolCallGuard = (
  call: { toolName: string; input: Record<string, unknown> },
  context: ToolCallGuardContext,
) => Promise<{ block: true; reason: string } | undefined>;
